-- =============================================================================
-- KISS Vocational Training Management System (KV-TMS)
-- Relational Database DDL Schema (3NF Compliant)
-- Database Engine: PostgreSQL / MySQL / H2 Relational Compatible
-- Generated: October 7, 2026
-- =============================================================================

-- 1. USER ACCOUNTS & AUTHENTICATION
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    contact_info VARCHAR(100),
    account_status VARCHAR(20) DEFAULT 'ACTIVE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. VOCATIONAL TRADE TRACKS
CREATE TABLE course_trades (
    trade_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    duration VARCHAR(50) NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. TRAINER / MASTER CRAFTSMEN PROFILES
CREATE TABLE trainers (
    trainer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    specialization VARCHAR(100) NOT NULL,
    trade_id BIGINT REFERENCES course_trades(trade_id) ON DELETE SET NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE'
);

-- 4. INDIGENOUS STUDENT ARTISANS
CREATE TABLE trainees (
    trainee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    trade_id BIGINT REFERENCES course_trades(trade_id) ON DELETE SET NULL,
    aadhaar_no VARCHAR(20) NOT NULL UNIQUE,
    bank_account VARCHAR(30) NOT NULL,
    status VARCHAR(20) DEFAULT 'ENROLLED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. PRACTICAL TRAINING LESSONS
CREATE TABLE trainings (
    training_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id BIGINT NOT NULL REFERENCES course_trades(trade_id) ON DELETE CASCADE,
    trainer_id BIGINT NOT NULL REFERENCES trainers(trainer_id) ON DELETE CASCADE,
    topic VARCHAR(150) NOT NULL,
    training_date DATE NOT NULL,
    practical_theory VARCHAR(20) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. COHORT ATTENDANCE MARKS
CREATE TABLE attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES trainees(trainee_id) ON DELETE CASCADE,
    training_id BIGINT NOT NULL REFERENCES trainings(training_id) ON DELETE CASCADE,
    attendance_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT uq_trainee_training UNIQUE (trainee_id, training_id)
);

-- 7. PRACTICAL CRAFTSMANSHIP ASSESSMENTS
CREATE TABLE assessments (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES trainees(trainee_id) ON DELETE CASCADE,
    training_id BIGINT NOT NULL REFERENCES trainings(training_id) ON DELETE CASCADE,
    score_marks DECIMAL(5,2) NOT NULL,
    assessment_date DATE NOT NULL,
    remarks TEXT
);

-- 8. FINISHED CRAFT PRODUCT CATALOG
CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(120) NOT NULL,
    category VARCHAR(50) NOT NULL,
    trade_id BIGINT NOT NULL REFERENCES course_trades(trade_id) ON DELETE CASCADE,
    unit_price DECIMAL(10,2) NOT NULL,
    stipend_rate DECIMAL(10,2) NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. WORKSHOP BATCH MANUFACTURING RUNS
CREATE TABLE productions (
    production_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    prod_date DATE NOT NULL,
    target_quantity INT NOT NULL,
    passed_quantity INT DEFAULT 0,
    rejected_quantity INT DEFAULT 0,
    status VARCHAR(20) DEFAULT 'SCHEDULED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 10. TWO-TIER INVENTORY (RAW & FINISHED)
CREATE TABLE inventory (
    inventory_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    item_type VARCHAR(30) NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(20) NOT NULL,
    stock_status VARCHAR(20) NOT NULL,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 11. POINT OF SALE (POS) TRANSACTIONS
CREATE TABLE sales_orders (
    sales_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no VARCHAR(40) NOT NULL UNIQUE,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    quantity_sold INT NOT NULL,
    sales_amount DECIMAL(10,2) NOT NULL,
    payment_mode VARCHAR(20) NOT NULL,
    sales_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 12. AI-DRIVEN DEMAND FORECASTING
CREATE TABLE forecasts (
    forecast_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    forecast_date DATE NOT NULL,
    predicted_demand INT NOT NULL,
    recommended_qty INT NOT NULL,
    model_info VARCHAR(100) DEFAULT 'Holt-Winters',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================================
-- PERFORMANCE INDEXES
-- =============================================================================
CREATE INDEX idx_users_username ON users(username);
CREATE INDEX idx_trainees_trade ON trainees(trade_id);
CREATE INDEX idx_attendance_date ON attendance(attendance_date);
CREATE INDEX idx_products_trade ON products(trade_id);
CREATE INDEX idx_sales_invoice ON sales_orders(invoice_no);
CREATE INDEX idx_inventory_item ON inventory(item_id, item_type);
